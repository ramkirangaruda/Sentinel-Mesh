// Generates the DEMO ML-DSA key pairs for the three nodes and writes
// src/common/demo_keys_l<level>.h. Build/run with tools/gen_demo_keys.sh.
//
// DEMO ONLY: the secret keys are committed to the repo and compiled into every
// image. That is acceptable for a lab measurement rig (the paper measures
// handshake energy, not key management) and is stated as such in
// paper/decisions.md. Never reuse these keys.
#include <cstdio>
#include <cstdint>
#include <vector>
#include "sentinel_pqc/pqc_params.h"

using namespace sentinel::pqc;

static void emit(FILE* f, const char* name, const std::vector<uint8_t>& v) {
    fprintf(f, "static const uint8_t %s[%zu] = {", name, v.size());
    for (size_t i = 0; i < v.size(); i++) {
        if (i % 24 == 0) fprintf(f, "\n  ");
        fprintf(f, "0x%02x,", v[i]);
    }
    fprintf(f, "\n};\n");
}

int main(int argc, char** argv) {
    if (argc < 2) { fprintf(stderr, "usage: gen_demo_keys <out.h>\n"); return 2; }
    FILE* f = fopen(argv[1], "w");
    if (!f) return 1;
    fprintf(f, "#pragma once\n#include <cstdint>\n\n"
               "// GENERATED by tools/gen_demo_keys.cpp -- %s signatures. DEMO KEYS: secret keys are public.\n"
               "// Do not edit; regenerate with tools/gen_demo_keys.sh.\n"
               "namespace sentinel::demo_keys {\n", SM_PQC_SIG_NAME);
    const char* nodes[] = {"FIELD1", "GATEWAY", "ATTACKER"};
    for (const char* n : nodes) {
        std::vector<uint8_t> pk(SIG_PK_BYTES), sk(SIG_SK_BYTES);
        if (SM_SIG(crypto_sign_keypair)(pk.data(), sk.data()) != 0) return 1;
        char nm[64];
        snprintf(nm, sizeof(nm), "SIG_PK_%s", n); emit(f, nm, pk);
        snprintf(nm, sizeof(nm), "SIG_SK_%s", n); emit(f, nm, sk);
    }
    fprintf(f, "} // namespace sentinel::demo_keys\n");
    fclose(f);
    return 0;
}
